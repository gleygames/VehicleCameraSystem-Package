namespace Gley.CameraSystem
{
    public class GeneratedOrbitConnectorPair
    {
        public GeneratedOrbitConnector LeftConnector { get; }
        public GeneratedOrbitConnector RightConnector { get; }

        public GeneratedOrbitConnectorPair(GeneratedOrbitConnector leftConnector, GeneratedOrbitConnector rightConnector)
        {
            LeftConnector = leftConnector;
            RightConnector = rightConnector;
        }
    }
}
